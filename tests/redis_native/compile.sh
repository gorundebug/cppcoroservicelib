#!/usr/bin/env bash
set -euo pipefail
cmake -S /workspace -B /probe/sdk-build \
 -DCMAKE_TOOLCHAIN_FILE=/workspace/build/Release/generators/conan_toolchain.cmake \
 -DCMAKE_BUILD_TYPE=Release -DCPPCOROSERVICELIB_DEPENDENCY_MODE=CONAN \
 -DCMAKE_PREFIX_PATH=/probe/install \
 -DCPPCOROSERVICELIB_ENABLE_REDISSTREAMS=ON \
 -DCPPCOROSERVICELIB_ENABLE_PULSAR=OFF -DCPPCOROSERVICELIB_ENABLE_NATS=OFF \
 -DCPPCOROSERVICELIB_ENABLE_GRPC=OFF -DCPPCOROSERVICELIB_ENABLE_KAFKA=OFF \
 -DCPPCOROSERVICELIB_ENABLE_OTEL=OFF -DCPPCOROSERVICELIB_ENABLE_CRON=OFF \
 -DCPPCOROSERVICELIB_BUILD_TESTS=ON -DUSE_CCACHE=OFF
cmake --build /probe/sdk-build --target cppcoroservicelib_redis_native_test -j3
